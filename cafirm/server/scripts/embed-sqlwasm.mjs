// Embeds the SQLite WebAssembly binary into a JS module so the Netlify Function needs no extra files.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const server = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const wasm = fs.readFileSync(path.join(server, 'node_modules/sql.js/dist/sql-wasm.wasm'));
fs.writeFileSync(path.join(server, 'src/sqlwasm.generated.js'), `// Generated by scripts/embed-sqlwasm.mjs – do not edit.\nexport const WASM_BASE64 = '${wasm.toString('base64')}';\n`);
console.log(`✔ Embedded sql-wasm.wasm (${Math.round(wasm.length / 1024)} KB)`);
