// Creates the one-time setup code used by the first-run screen on Netlify (kept if the file already exists).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const file = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'setup-code.generated.js');
if (!fs.existsSync(file)) fs.writeFileSync(file, `// Generated by scripts/setup-code.mjs – do not edit or commit.\nexport const SETUP_CODE = '${crypto.randomBytes(9).toString('base64url')}';\n`);
console.log(`✔ First-run setup code: ${fs.readFileSync(file, 'utf8').match(/'(.+)'/)[1]}   (needed once, to create the Administrator)`);
