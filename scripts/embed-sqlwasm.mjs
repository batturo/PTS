// Embeds the SQLite WebAssembly binary into a JS module so the bundled Netlify Function needs no extra files.
import fs from 'node:fs';
const wasm = fs.readFileSync('server/node_modules/sql.js/dist/sql-wasm.wasm');
fs.writeFileSync('server/src/sqlwasm.generated.js', `// Generated by scripts/embed-sqlwasm.mjs – do not edit.\nexport const WASM_BASE64 = '${wasm.toString('base64')}';\n`);
console.log(`✔ Embedded sql-wasm.wasm (${Math.round(wasm.length / 1024)} KB)`);
